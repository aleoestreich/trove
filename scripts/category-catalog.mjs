// Regenerates src/data/categoryCatalog.ts from the icon pack's categories.json
// (colours, icon order, default categories). Run after updating the pack:
//   node scripts/category-catalog.mjs
// A test checks the two stay in sync.
import { readFileSync, writeFileSync } from 'node:fs'

const json = JSON.parse(readFileSync(new URL('../src/assets/icons/categories/categories.json', import.meta.url), 'utf8'))
const colors = Object.keys(json.colors)
const icons = json.icons.flatMap((g) => g.icons.map((i) => i.key))
const defaults = json.defaultCategories.map((c) => ({
  id: c.id,
  type: c.type,
  color: c.color,
  icon: c.icon,
  name: c.name,
  subcategories: c.subcategories,
}))

const out = `// Generated by scripts/category-catalog.mjs from src/assets/icons/categories/categories.json.
// Do not edit by hand. Shared by the app and the server, so it imports nothing.

/** The 24 category colours, in picker order. A category stores the key; the CSS token is --cat-<key>. */
export const CATEGORY_COLORS = ${JSON.stringify(colors)} as const
export type CategoryColor = (typeof CATEGORY_COLORS)[number]

/** Colour names for the picker's labels. */
export const CATEGORY_COLOR_NAMES: Record<CategoryColor, { en: string; pt: string }> = ${JSON.stringify(
  Object.fromEntries(colors.map((k) => [k, json.colors[k].name])),
)}

/** The 54 category icon keys (file names in src/assets/icons/categories/), in picker order. */
export const CATEGORY_ICONS = ${JSON.stringify(icons)} as const
export type CategoryIconKey = (typeof CATEGORY_ICONS)[number]

/** Icon labels as the pack has them (English); the app shows the pt-BR names in src/i18n/messages.ts. */
export const CATEGORY_ICON_LABELS: Record<string, string> = ${JSON.stringify(
  Object.fromEntries(json.icons.flatMap((g) => g.icons.map((i) => [i.key, i.label]))),
)}

export interface DefaultCategory {
  id: string
  type: 'expense' | 'income'
  color: CategoryColor
  icon: CategoryIconKey
  name: { en: string; pt: string }
  subcategories: { en: string; pt: string }[]
}

/** Seeded on first run, with the Portuguese names. */
export const DEFAULT_CATEGORIES: DefaultCategory[] = ${JSON.stringify(defaults, null, 2)}
`
writeFileSync(new URL('../src/data/categoryCatalog.ts', import.meta.url), out)
console.log(`categoryCatalog.ts: ${colors.length} colours, ${icons.length} icons, ${defaults.length} default categories`)
